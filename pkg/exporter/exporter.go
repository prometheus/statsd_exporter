const (
	defaultHelp = "Metric autogenerated by statsd_exporter."
	regErrF     = "Failed to update metric"

	// DefaultSetFlushInterval is how often the distinct values received for
	// each StatsD set are counted and the sets are emptied.
	DefaultSetFlushInterval = time.Minute
)

type Registry interface {
	GetCounter(metricName string, labels prometheus.Labels, help string, mapping *mapper.MetricMapping, metricsCount *prometheus.GaugeVec) (prometheus.Counter, error)
	GetGauge(metricName string, labels prometheus.Labels, help string, mapping *mapper.MetricMapping, metricsCount *prometheus.GaugeVec) (prometheus.Gauge, error)
	GetHistogram(metricName string, labels prometheus.Labels, help string, mapping *mapper.MetricMapping, metricsCount *prometheus.GaugeVec) (prometheus.Observer, error)
	GetSummary(metricName string, labels prometheus.Labels, help string, mapping *mapper.MetricMapping, metricsCount *prometheus.GaugeVec) (prometheus.Observer, error)
	RemoveStaleMetrics()
}

var (
	// ErrClearMetricsUnsupported indicates that the configured registry cannot clear metrics.
	ErrClearMetricsUnsupported = errors.New("registry does not support clearing metrics")
	// ErrExporterNotRunning indicates that the exporter event loop is not running.
	ErrExporterNotRunning = errors.New("exporter listener is not running")
)

type clearableRegistry interface {
	ClearMetrics() int
}

type clearMetricsRequest struct {
	result chan clearMetricsResult
}

type clearMetricsResult struct {
	cleared int
	err     error
}

type Exporter struct {
	Mapper                *mapper.MetricMapper
	Registry              Registry
	Logger                *slog.Logger
	EventsActions         *prometheus.CounterVec
	EventsUnmapped        prometheus.Counter
	ErrorEventStats       *prometheus.CounterVec
	EventStats            *prometheus.CounterVec
	ConflictingEventStats *prometheus.CounterVec
	MetricsCount          *prometheus.GaugeVec
	clearMetrics          chan clearMetricsRequest
	listenStateMtx        sync.RWMutex
	listening             bool
	listenDone            chan struct{}

	// SetFlushInterval is how often the number of distinct values seen for
	// each StatsD set is published and the sets are emptied, like a StatsD
	// flush. Zero or less disables the periodic flush.
	SetFlushInterval time.Duration

	sets map[string]*setState
}

// setState tracks the distinct values one StatsD set received since the last
// flush, and the gauge the count is published on.
type setState struct {
	gauge  prometheus.Gauge
	values map[string]struct{}
}

// Listen handles all events sent to the given channel sequentially. It
// terminates when the channel is closed.
func (b *Exporter) Listen(e <-chan event.Events) {
	removeStaleMetricsTicker := clock.NewTicker(time.Second)
	defer removeStaleMetricsTicker.Stop()

	b.listenStateMtx.Lock()
	b.listening = true
	b.listenDone = make(chan struct{})
	b.clearMetrics = make(chan clearMetricsRequest)
	done := b.listenDone
	clearMetrics := b.clearMetrics
	b.listenStateMtx.Unlock()

	defer func() {
		b.listenStateMtx.Lock()
		b.listening = false
		close(done)
		b.listenStateMtx.Unlock()
	}()

	// A plain ticker on purpose: the mocked clock ticker is shared, and tests
	// rely on every mocked tick reaching RemoveStaleMetrics.
	var setFlush <-chan time.Time
	if b.SetFlushInterval > 0 {
		setFlushTicker := time.NewTicker(b.SetFlushInterval)
		defer setFlushTicker.Stop()
		setFlush = setFlushTicker.C
	}

	for {
		select {
		case <-removeStaleMetricsTicker.C:
			b.Registry.RemoveStaleMetrics()
		case request := <-clearMetrics:
			result := b.clearRegistryMetrics()
			if result.err == nil {
				// The cleared gauges are gone, so pending set values would
				// otherwise be published on detached gauges at the next flush.
				b.sets = nil
			}
			request.result <- result
		case <-setFlush:
			b.FlushSets()
		case events, ok := <-e:
			if !ok {
				b.Logger.Debug("Channel is closed. Break out of Exporter.Listener.")
				return
			}
			for _, event := range events {
				b.handleEvent(event)
			}
		}
	}
}

// ClearMetrics clears all dynamically registered StatsD time series.
//
// Clearing runs inside the exporter event loop, so no StatsD events are
// processed until it finishes. With a large number of registered series this
// can take a while and the exporter may appear to hang.
func (b *Exporter) ClearMetrics(ctx context.Context) (int, error) {
	if ctx == nil {
		ctx = context.Background()
	}

	done, clearMetrics, ok := b.listenState()
	if !ok {
		return 0, ErrExporterNotRunning
	}

	request := clearMetricsRequest{
		result: make(chan clearMetricsResult, 1),
	}

	select {
	case clearMetrics <- request:
	case <-done:
		return 0, ErrExporterNotRunning
	case <-ctx.Done():
		return 0, ctx.Err()
	}

	select {
	case result := <-request.result:
		return result.cleared, result.err
	case <-ctx.Done():
		return 0, ctx.Err()
	}
}

func (b *Exporter) listenState() (<-chan struct{}, chan<- clearMetricsRequest, bool) {
	b.listenStateMtx.RLock()
	defer b.listenStateMtx.RUnlock()
	return b.listenDone, b.clearMetrics, b.listening
}

func (b *Exporter) clearRegistryMetrics() clearMetricsResult {
	clearable, ok := b.Registry.(clearableRegistry)
	if !ok {
		return clearMetricsResult{err: ErrClearMetricsUnsupported}
	}
	return clearMetricsResult{cleared: clearable.ClearMetrics()}
}

// handleEvent processes a single Event according to the configured mapping.
func (b *Exporter) handleEvent(thisEvent event.Event) {
	mapping, labels, present := b.Mapper.GetMapping(thisEvent.MetricName(), thisEvent.MetricType())
	if mapping == nil {
		mapping = &mapper.MetricMapping{}
		if b.Mapper.Defaults.Ttl != 0 {
			mapping.Ttl = b.Mapper.Defaults.Ttl
		}
	}

	if mapping.Action == mapper.ActionTypeDrop {
		b.EventsActions.WithLabelValues("drop").Inc()
		return
	}

	metricName := ""

	help := defaultHelp
	if mapping.HelpText != "" {
		help = mapping.HelpText
	}

	prometheusLabels := thisEvent.Labels()
	if present {
		if mapping.Name == "" {
			b.Logger.Debug("The mapping generates an empty metric name", "metric_name", thisEvent.MetricName(), "match", mapping.Match)
			b.ErrorEventStats.WithLabelValues("empty_metric_name").Inc()
			return
		}
		metricName = mapper.EscapeMetricName(mapping.Name)
		for label, value := range labels {
			if _, ok := prometheusLabels[label]; mapping.HonorLabels && ok {
				continue
			}

			prometheusLabels[label] = value
		}
		b.EventsActions.WithLabelValues(string(mapping.Action)).Inc()
	} else {
		b.EventsUnmapped.Inc()
		metricName = mapper.EscapeMetricName(thisEvent.MetricName())
	}

	eventValue := thisEvent.Value()
	if mapping.Scale.Set {
		eventValue *= mapping.Scale.Val
	}

	switch ev := thisEvent.(type) {
	case *event.CounterEvent:
		// We don't accept negative values for counters. Incrementing the counter with a negative number
		// will cause the exporter to panic. Instead we will warn and continue to the next event.
		if eventValue < 0.0 {
			b.Logger.Debug("counter must be non-negative value", "metric", metricName, "event_value", eventValue)
			b.ErrorEventStats.WithLabelValues("illegal_negative_counter").Inc()
			return
		}

		counter, err := b.Registry.GetCounter(metricName, prometheusLabels, help, mapping, b.MetricsCount)
		if err == nil {
			counter.Add(eventValue)
			b.EventStats.WithLabelValues("counter").Inc()
		} else {
			b.Logger.Debug(regErrF, "metric", metricName, "error", err)
			b.ConflictingEventStats.WithLabelValues("counter", metricName).Inc()
		}

	case *event.GaugeEvent:
		gauge, err := b.Registry.GetGauge(metricName, prometheusLabels, help, mapping, b.MetricsCount)

		if err == nil {
			if ev.GRelative {
				gauge.Add(eventValue)
			} else {
				gauge.Set(eventValue)
			}
			b.EventStats.WithLabelValues("gauge").Inc()
		} else {
			b.Logger.Debug(regErrF, "metric", metricName, "error", err)
			b.ConflictingEventStats.WithLabelValues("gauge", metricName).Inc()
		}

	case *event.ObserverEvent:
		t := mapper.ObserverTypeDefault
		if mapping != nil {
			t = mapping.ObserverType
		}
		if t == mapper.ObserverTypeDefault {
			t = b.Mapper.Defaults.ObserverType
		}

		switch t {
		case mapper.ObserverTypeHistogram:
			histogram, err := b.Registry.GetHistogram(metricName, prometheusLabels, help, mapping, b.MetricsCount)
			if err == nil {
				histogram.Observe(eventValue)
				b.EventStats.WithLabelValues("observer").Inc()
			} else {
				b.Logger.Debug(regErrF, "metric", metricName, "error", err)
				b.ConflictingEventStats.WithLabelValues("observer", metricName).Inc()
			}

		case mapper.ObserverTypeDefault, mapper.ObserverTypeSummary:
			summary, err := b.Registry.GetSummary(metricName, prometheusLabels, help, mapping, b.MetricsCount)
			if err == nil {
				summary.Observe(eventValue)
				b.EventStats.WithLabelValues("observer").Inc()
			} else {
				b.Logger.Debug(regErrF, "metric", metricName, "error", err)
				b.ConflictingEventStats.WithLabelValues("observer", metricName).Inc()
			}

		default:
			b.Logger.Error("unknown observer type", "type", t)
			os.Exit(1)
		}

	case *event.SetEvent:
		gauge, err := b.Registry.GetGauge(metricName, prometheusLabels, help, mapping, b.MetricsCount)
		if err == nil {
			b.addToSet(metricName, prometheusLabels, gauge, ev.SValue)
			b.EventStats.WithLabelValues("set").Inc()
		} else {
			b.Logger.Debug(regErrF, "metric", metricName, "error", err)
			b.ConflictingEventStats.WithLabelValues("set", metricName).Inc()
		}

	default:
		b.Logger.Debug("Unsupported event type")
		b.EventStats.WithLabelValues("illegal").Inc()
	}
}

// addToSet records value as a member of the set identified by metricName and
// labels.
func (b *Exporter) addToSet(metricName string, labels prometheus.Labels, gauge prometheus.Gauge, value string) {
	if b.sets == nil {
		b.sets = map[string]*setState{}
	}

	key := setKey(metricName, labels)
	state, ok := b.sets[key]
	if !ok {
		state = &setState{values: map[string]struct{}{}}
		b.sets[key] = state
	}
	// The registry can hand out a new gauge after the old one expired, so
	// always publish on the latest one.
	state.gauge = gauge
	state.values[value] = struct{}{}
}

// FlushSets sets the gauge of every StatsD set to the number of distinct
// values it received since the previous flush, and empties the sets. A set
// that received nothing reports 0 once and is then forgotten until it
// receives a value again. Listen calls it every SetFlushInterval.
func (b *Exporter) FlushSets() {
	for key, state := range b.sets {
		state.gauge.Set(float64(len(state.values)))
		if len(state.values) == 0 {
			delete(b.sets, key)
			continue
		}
		state.values = map[string]struct{}{}
	}
}

// setKey identifies a set by its metric name and label values.
func setKey(metricName string, labels prometheus.Labels) string {
	names := make([]string, 0, len(labels))
	for name := range labels {
		names = append(names, name)
	}
	sort.Strings(names)

	var key strings.Builder
	key.WriteString(metricName)
	for _, name := range names {
		key.WriteByte(0xff)
		key.WriteString(name)
		key.WriteByte(0xff)
		key.WriteString(labels[name])
	}
	return key.String()
}

func NewExporter(reg prometheus.Registerer, mapper *mapper.MetricMapper, logger *slog.Logger, eventsActions *prometheus.CounterVec, eventsUnmapped prometheus.Counter, errorEventStats, eventStats, conflictingEventStats *prometheus.CounterVec, metricsCount *prometheus.GaugeVec) *Exporter {
	return &Exporter{
		Mapper:                mapper,
		Registry:              registry.NewRegistry(reg, mapper),
		Logger:                logger,
		EventsActions:         eventsActions,
		EventsUnmapped:        eventsUnmapped,
		ErrorEventStats:       errorEventStats,
		EventStats:            eventStats,
		ConflictingEventStats: conflictingEventStats,
		MetricsCount:          metricsCount,
		SetFlushInterval:      DefaultSetFlushInterval,
	}
}
